"""Deterministic code templates - the offline / fallback generator for BUILD.

Every template turns the same inputs (step plan, parameter keys, optional API plan) into a
runnable suite with the same contract as the AI generator:

  * target URL from the ``TARGET_URL`` env var,
  * every parameter value from ``payload.json`` (path in ``UNDERSTUDY_PAYLOAD``), secrets from
    ``UNDERSTUDY_SECRET_<KEY>`` env vars - values are NEVER embedded in code,
  * a locator cascade per element: primary selector -> fallback selectors -> visible label,
  * one ``STEP <n> OK|FAILED`` log line per step and a non-zero exit code on failure.

Literals (selectors, labels, descriptions) are embedded with language-correct escaping
(``json.dumps`` yields valid Python/JS/Java string literals; Robot uses its own escaping).
"""
from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Optional, Tuple

HEADER = "Generated by Understudy - edit freely. Run with the run.sh / run.bat launcher."


def _q(s: Any) -> str:
    return json.dumps("" if s is None else str(s))


def _comment(s: Any) -> str:
    return re.sub(r"[\r\n]+", " ", str(s or "")).replace("*/", "* /")[:160]


def _selectors(step: Dict[str, Any]) -> List[str]:
    out = []
    for s in [step.get("selector")] + list(step.get("fallback_selectors") or []):
        if s and s not in out:
            out.append(str(s))
    return out


def _wait_ms(step: Dict[str, Any]) -> int:
    try:
        return max(0, min(10000, int(float(step.get("value") or 1000))))
    except (TypeError, ValueError):
        return 1000


def _secret_keys(params: List[Dict[str, Any]]) -> List[str]:
    return [p["key"] for p in params if p.get("type") == "secret"]


