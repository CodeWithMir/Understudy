def page_tokens(steps: List[Dict[str, Any]], page_urls: Optional[List[str]]) -> List[Dict[str, Any]]:
    """9.4: a navigate step to one of the user's pages becomes ``${TARGET_URL_<n>}`` (the code reads that page's
    address from the environment, so the exported suite can run against another environment). Copies the steps."""
    urls = [str(u or "").rstrip("/") for u in (page_urls or [])]
    out = []
    for st in steps:
        st = dict(st)
        v = str(st.get("value") or "").rstrip("/")
        if st.get("action") == "navigate" and v and len(urls) > 1 and v in urls:
            st["value"] = f"${{TARGET_URL_{urls.index(v) + 1}}}"
        out.append(st)
    return out


