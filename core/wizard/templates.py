        body.append(f"            step = {n}")
        if a == "navigate":
            body.append(f"            page.goto(resolve_url({_q(st.get('value') or '')}), wait_until=\"domcontentloaded\")")
        elif a == "fill":
            body.append(f"            locate(page, {json.dumps(sels)}, {_q(label)}).fill(str(payload[{_q(key)}]))")
        elif a == "select":
            body.append(f"            select(locate(page, {json.dumps(sels)}, {_q(label)}), str(payload[{_q(key)}]))")
        elif a == "check":
            body.append(f"            el = locate(page, {json.dumps(sels)}, {_q(label)})")
            body.append(f"            el.check() if truthy(payload[{_q(key)}]) else el.uncheck()")
