def locate(driver, selectors, label):
    """Self-healing locator cascade: CSS selectors -> <label> text -> placeholder -> button text."""
    deadline = time.time() + STEP_TIMEOUT_S
    while time.time() < deadline:
        for sel in selectors:
            try:
                is_xpath = sel.startswith(("//", "(/", "xpath="))
                found = driver.find_elements(By.XPATH if is_xpath else By.CSS_SELECTOR,
                                             sel[6:] if sel.startswith("xpath=") else sel)
                if found:
                    return found[0]
            except Exception:
                continue
        if label:
            for lab in driver.find_elements(By.XPATH, "//label"):
                if label.lower() in (lab.text or "").lower() and lab.get_attribute("for"):
                    found = driver.find_elements(By.ID, lab.get_attribute("for"))
                    if found:
                        return found[0]
            # a label that sits next to its field (no 'for'), e.g. forms whose ids change on every load
            found = driver.find_elements(By.XPATH, "//label[normalize-space(.)=%s]/following-sibling::*[self::input or "
                                                   "self::select or self::textarea][1]" % json.dumps(label))
            if found:
                return found[0]
            found = driver.find_elements(By.XPATH, "//*[@placeholder=%s]" % json.dumps(label))
            if found:
                return found[0]
            # a button by its text, any case: <button>, role="button", <input type=submit|button value=...>
            found = driver.find_elements(By.XPATH, BUTTON_XPATH % json.dumps(label.lower()))
            if found:
                return found[0]
        time.sleep(0.25)
    raise RuntimeError(f"Element not found (selectors={{selectors}}, label={{label!r}})")


