"""STEP 5 - EXPORT: package the verified automation as a self-contained ZIP.

Contents
    README.md                 beginner guide: what it does, how to install and run, how to change values
    <suite files>             generated automation code (entry file + config)
    payload.json              the verified, SOP-compliant payload (secrets excluded)
    .env.example              TARGET_URL + one UNDERSTUDY_SECRET_<KEY>= line per secret (empty)
    config/environment.json   framework, runtime, target URL, dependency plan, generator provenance
    <manifest>                requirements.txt / package.json / pom.xml / Gemfile / go.mod / .csproj
    run.sh, run.ps1, run.bat  launchers: install dependencies, run, write a report to results/<run id>/
    reporting/                the report writer (POSIX awk) and the HTML template the launchers use
    governance/               sop.txt, rules.json (user-confirmed), compliance_report.json
    evidence/                 evidence_log.json (all 5 step results), EVIDENCE.md, execution_log.txt
The ZIP is produced only when all five pillars are PASS (enforced by session.export and again by the
download endpoints).
"""
from __future__ import annotations

import io
import json
import zipfile
from datetime import datetime
from typing import Any, Dict, List, Optional

from core.wizard import WIZARD_VERSION
from core.wizard import dependency_lock, dependency_resolver, payload_schema
from core.wizard.executor import payload_for_disk
from core.wizard.frameworks import FrameworkSpec


def _admin_versions(tool_id: str) -> Dict[str, Any]:
    try:
        from core.wizard import admin_policy
        return admin_policy.tool_version_policy(tool_id)
    except Exception:
        return {}


def _versions_md(lock: Dict[str, Any]) -> str:
    rows = "\n".join(f"| `{p['name']}` | `{p['requested']}` | `{p.get('installed') or 'resolved on install'}` |"
                      f"{' extra (needed by the generated code)' if p.get('extra') else ''} |"
                      for p in lock.get("packages") or [])
    return ("| Package | Requested | Verified run used | Note |\n|---|---|---|---|\n" + rows) if rows else "(no packages)"


def _pages(s: Dict[str, Any]) -> List[str]:
    urls = [u for u in (s.get("target_urls") or []) if u]
    if s.get("target_url") and s["target_url"] not in urls:
        urls.insert(0, s["target_url"])
    return urls


def _pages_md(s: Dict[str, Any]) -> str:
    urls = _pages(s)
    if len(urls) < 2:
        return ""
    rows = "\n".join(f"| `TARGET_URL_{i}` | `{u}` |" for i, u in enumerate(urls, 1))
    return ("\n## Pages\nThe process visits these pages. The code reads each address from an environment variable "
            "(`TARGET_URL` is page 1; `TARGET_URLS` has all of them) - change them in `.env` to run against another "
            "environment.\n\n| Variable | Page |\n|---|---|\n" + rows + "\n")


def _env_md(env_lines: Optional[List[str]]) -> str:
    from core.wizard.export_readme import _env_vars
    rows = _env_vars(env_lines or [])
    if not rows:
        return ""
    return ("\n## Environment variables\nSet them in `.env` (copy `.env.example`); real environment variables win.\n\n"
            "| Variable | Required | Meaning |\n|---|---|---|\n"
            + "\n".join(f"| `{e['name']}` | {e['required']} | {e['meaning']} |" for e in rows) + "\n")


def _readme(s: Dict[str, Any], spec: FrameworkSpec, lock: Optional[Dict[str, Any]] = None,
            env_lines: Optional[List[str]] = None) -> str:
    params = s["parameters"]
    rows = "\n".join(f"| `{p['key']}` | {p.get('label', '')} | {'*(secret - set in .env)*' if p.get('type') == 'secret' else '`' + str(p.get('value')) + '`'} |"
                     for p in params)
    secrets = [p for p in params if p.get("type") == "secret"]
    steps = "\n".join(f"{st['order']}. {st.get('description') or st['action']}" for st in s["analysis"]["steps"])
    rules = "\n".join(f"- {r['plain_english']}" for r in s.get("rules") or [] if r.get("enabled", True)) or "- (no SOP rules)"
    run_cmd = " ".join(t.replace("{entry}", spec.entry_file) for t in spec.run_command)
    return f"""# {s['analysis'].get('process_name', 'Automation')} - {spec.name}

Generated by **Understudy** on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')} and
**tested end-to-end** (Watch -> Govern -> Build -> Execute -> Export all PASSED; the run completed) against `{s['target_url']}`{f" and {len(_pages(s)) - 1} more page(s)" if len(_pages(s)) > 1 else ""}.
{_pages_md(s)}
## What this automation does
{s['analysis'].get('summary', '')}

Steps:
{steps}

{_agentic_md(spec)}## Quick start
1. Install the toolchain for **{spec.language}** ({', '.join(dependency_resolver.TOOLCHAINS.get(spec.ecosystem, [])) or 'no extra tools'}).
2. Copy `.env.example` to `.env` and check `TARGET_URL`{' and the other page addresses' if len(_pages(s)) > 1 else ''}{' and fill in the secrets' if secrets else ''}.
3. Run it:
   - macOS / Linux: `bash run.sh`
   - Windows: `run.bat`

The launcher installs the dependencies listed in `{', '.join(dependency_resolver.manifest_files(spec).keys()) or 'n/a'}` and then runs:

```
{run_cmd}
```

{_env_md(env_lines)}
## Dependency versions
These are the exact versions the verified run used (also in `config/dependency_lock.json`); the manifest pins them,
so your machine installs the same ones.

{_versions_md(lock or {})}

## Changing the data (payload)
All business values live in **`payload.json`** - the code never contains them. Edit the file (or point
`UNDERSTUDY_PAYLOAD` at another JSON file) to run the same process with different data.

| Key | Meaning | Verified value |
|---|---|---|
{rows}

> The SOP rules below are part of the script: before step 1 it checks `payload.json` against `governance.json`
> and prints `GOVERN OK` - or `GOVERN FAILED: <why>` and stops before it touches the application. Check a new
> payload on its own with the checker next to the script (e.g. `python understudy_governance.py payload.json` or
> `node understudy_governance.js payload.json`).

## SOP rules (checked by the script before step 1)
{rules}

## Folder guide
- `config/environment.json` - framework, runtime and dependency details
- `governance.json` + `understudy_governance.*` - the SOP rules and the checker the script runs before step 1
- `governance/` - your SOP text, the confirmed rules and the compliance report
- `evidence/` - the run log and the step results of the run that passed in Understudy
- `results/` - created by every `run.sh` / `run.bat` run: `results/<run id>/understudy-report.html` (pass/fail, SOP
  check, every step, what failed, the full log), `understudy-report.json`, `run.log` (secrets masked) and, for pytest,
  `junit.xml`; `results/latest.html` opens the newest report
- `reporting/` - the report writer and page template the launchers use

Every step prints `STEP <n> OK` or `STEP <n> FAILED: <reason>`; the process exits with a non-zero code on failure,
so you can plug it straight into CI.
"""


def _agentic_md(spec: FrameworkSpec) -> str:
    if spec.category != "agentic":
        return ""
    script = (f"`{spec.entry_file}` is the agentic script for this process (each `agent.step` is a goal Gemini "
              "achieves on the live page; `understudy_agent.py` is the runtime with the guard rails)")
    return (f"## Agentic automation\n**{spec.name}** is an agentic tool: an AI agent (Gemini) decides every action on "
            f"the live page each time it runs, instead of replaying fixed selectors. {script}. It needs your Gemini "
            "API key in `.env` as `UNDERSTUDY_SECRET_GEMINI_API_KEY` (never commit it). The run log shows every "
            "decision the agent made (`AGENT step <n>: ...`).\n\n")


def _evidence_md(s: Dict[str, Any]) -> str:
    lines = [f"# Evidence - session {s['session_id']}", "", "Target: " + ", ".join(f"`{u}`" for u in _pages(s)), "", "| Pillar | Status | Reason |",
             "|---|---|---|"]
    for name in ("WATCH", "BUILD", "GOVERN", "BUILD-EXECUTE", "EXPORT"):
        p = s["pillars"].get(name) or {}
        lines.append(f"| {name} | {p.get('status', '-')} | {str(p.get('reason', '')).replace('|', '/')[:160]} |")
    ex = s.get("execution") or {}
    lines += ["", "## Run", f"Status: {ex.get('status', '-')} · strategy: {ex.get('strategy', '-')} · "
              f"{ex.get('duration_ms', '-')} ms · attempt {ex.get('attempt', '-')}", ""]
    if s.get("retry", {}).get("history"):
        lines += ["", "## Self-healing retries"]
        for h in s["retry"]["history"]:
            lines.append(f"- Attempt {h.get('attempt')}: {h.get('category')} - {h.get('diagnosis', '')[:200]} -> {h.get('outcome')}")
    return "\n".join(lines) + "\n"


def env_example_lines(s: Dict[str, Any], spec: FrameworkSpec) -> List[str]:
    """The ZIP's .env.example (also what the README must explain)."""
    params: List[Dict[str, Any]] = s["parameters"]
    secrets = [p for p in params if p.get("type") == "secret"]
    env_example = [f"TARGET_URL={s['target_url']}", "UNDERSTUDY_PAYLOAD=payload.json", "HEADLESS=true"]
    pages = _pages(s)
    if len(pages) > 1:                         # 9.4: every page the process visits, read by the code from the env
        env_example += ["", "# The pages the process visits (TARGET_URL_1 is TARGET_URL)"]
        env_example += [f"TARGET_URL_{i}={u}" for i, u in enumerate(pages, 1)]
        env_example += ["TARGET_URLS=" + " ".join(pages)]
    env_example += [f"UNDERSTUDY_SECRET_{p['key'].upper()}=" for p in secrets]
    if spec.category == "agentic":            # 9.8: the agent calls Gemini - the key is never in the package
        env_example += ["", "# Agentic tool: your Gemini API key (https://aistudio.google.com/apikey) and the model",
                        "UNDERSTUDY_SECRET_GEMINI_API_KEY=",
                        "UNDERSTUDY_AGENT_MODEL=" + str(((s.get("execution") or {}).get("agent_model"))
                                                        or (spec.agent or {}).get("model") or "gemini-flash-latest")]
        from core.wizard import agent_stacks           # 9.9: the browser stack this agentic tool runs on
        env_example += ["# Browser stack of this agentic tool (set up by your admin): playwright | selenium, and the "
                        "browser"] + [f"{k}={v}" for k, v in agent_stacks.run_env(spec).items()]
    # Runtime settings self-healing found necessary on the Understudy server - commented out, because the paths are
    # the SERVER's; uncomment and adjust them only if the same browser/driver problem happens on your machine.
    repairs = {k: v for k, v in (s.get("runtime_env") or {}).items() if not k.startswith("__")}
    if spec.id in ("selenium-python", "robot-framework") or repairs:
        env_example += ["", "# Browser selection (Selenium): chrome (default) | edge | firefox. Point at a specific install",
                        "# if Selenium says 'The browser path is not a valid file' / 'Unable to obtain driver'."]
        if repairs:
            env_example += ["# Understudy's self-healing used these on its server:"]
            env_example += [f"# {k}={v}" for k, v in sorted(repairs.items())]
        else:
            env_example += ["# SELENIUM_BROWSER=chrome", "# CHROME_BINARY=C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
                            "# EDGE_BINARY=C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe"]
    return env_example


def build_zip(s: Dict[str, Any], spec: FrameworkSpec) -> bytes:
    buf = io.BytesIO()
    params: List[Dict[str, Any]] = s["parameters"]
    env_example = env_example_lines(s, spec)
    environment = {
        "generated_by": f"Understudy {WIZARD_VERSION}",
        "runtime_repairs": s.get("runtime_repairs") or [],
        "package_versions_used": (s.get("dependencies") or {}).get("versions") or [],
        "generated_at": datetime.utcnow().isoformat(),
        "session_id": s["session_id"],
        "target_url": s["target_url"],
        "target_urls": _pages(s),
        "complexity": {k: (s.get("complexity") or {}).get(k) for k in ("score", "level", "summary")}
        if s.get("complexity") else None,
        "framework": {k: v for k, v in spec.to_dict().items() if k not in ("pros", "cons")},
        "code_generator": {k: s["suite"].get(k) for k in ("generator", "agent_source", "model")},
        "dependency_plan": dependency_resolver.plan_for(spec).to_dict() | {"env_dir": "(server-side cache, not shipped)"},
        "execution_strategy": (s.get("execution") or {}).get("strategy"),
        "build_agent": {k: (s.get("suite") or {}).get("agent", {}).get(k) for k in ("rounds", "verified_locators",
                                                                                  "page_loads")},
    }
    evidence_log = {"session_id": s["session_id"], "overall_status": "PASS", "pillars_passed": "5/5",
                    "pillars": s["pillars"], "retry": s.get("retry"), "security_events": s.get("security_events", [])}
    # Same packages, same versions as the verified run: every manifest is rebuilt from the run's spec and pinned to
    # the versions that were really installed in the sandbox (core/wizard/dependency_lock.py).
    versions_report = (s.get("dependencies") or {}).get("versions") or []
    exact = dependency_lock.exact_versions(versions_report)
    suite_files = dependency_lock.apply_to_files(spec, s["suite"]["files"], exact)
    pinned_spec = dependency_lock.pinned(spec, exact)
    lock = dependency_lock.lock_report(spec, versions_report, (s.get("dependency_lock") or {}).get("extras") or [],
                                       (s.get("dependency_lock") or {}).get("chosen_version"),
                                       _admin_versions(spec.id))
    lock["manifest_files"] = sorted(n for n in suite_files if n in dependency_lock.ALL_MANIFESTS)
    environment["dependency_lock"] = lock
    # 9.9: the README is written by Gemini from the package's facts (checked; Understudy's own README otherwise)
    from core.wizard import export_readme
    launchers = dependency_resolver.setup_scripts(pinned_spec)
    shipped = sorted(set(suite_files) | set(launchers) | {"payload.json", "payload.schema.json", ".env.example",
                                                           "config/environment.json", "config/dependency_lock.json",
                                                           "governance/", "evidence/"})
    readme = export_readme.write(s, export_readme.facts(s, pinned_spec, lock, env_example, shipped, launchers),
                                 fallback=_readme(s, pinned_spec, lock, env_example))
    environment["readme"] = {k: readme.get(k) for k in ("source", "model", "added", "problems")}
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("README.md", readme["markdown"])
        for path, content in suite_files.items():
            z.writestr(path, content)
        z.writestr("config/dependency_lock.json", json.dumps(lock, indent=2, default=str))
        z.writestr("payload.json", json.dumps(payload_for_disk(params), indent=2) + "\n")
        z.writestr("payload.schema.json", json.dumps(payload_schema.schema_json(params), indent=2))
        z.writestr(".env.example", "\n".join(env_example) + "\n")
        try:
            from core.wizard import skills
            for path, md in skills.markdown_for_export(spec.id, s["target_url"]).items():
                z.writestr(path, md)          # lessons learned on the Understudy machine, for your own agents/CI
        except Exception:
            pass
        z.writestr("config/environment.json", json.dumps(environment, indent=2, default=str))
        for name, content in launchers.items():
            info = zipfile.ZipInfo(name)
            info.external_attr = (0o755 << 16) if name.endswith(".sh") else (0o644 << 16)
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, content)
        z.writestr("governance/sop.txt", s.get("sop_text") or "")
        z.writestr("governance/rules.json", json.dumps(s.get("rules") or [], indent=2))
        z.writestr("governance/compliance_report.json", json.dumps(s.get("compliance") or {}, indent=2, default=str))
        z.writestr("evidence/evidence_log.json", json.dumps(evidence_log, indent=2, default=str))
        z.writestr("evidence/EVIDENCE.md", _evidence_md(s))
        z.writestr("evidence/execution_log.txt", "\n".join((s.get("execution") or {}).get("logs", [])) + "\n")
        z.writestr(".gitignore", ".env\n.venv/\nnode_modules/\nresults/\ntarget/\n")
    return buf.getvalue()
